const pieceOrder = ["PAWN", "ROOK", "KNIGHT", "BISHOP", "QUEEN", "KING"];

export function pieceBounds(theme, type, color) {
  const layout = layouts[theme === "warm" ? "classic" : theme] ?? layouts.classic;
  const column = Math.max(0, pieceOrder.indexOf(type));
  return layout[color === "BLACK" ? 1 : 0][column];
}

export function classicPieceHeight(type) {
  const whiteHeight = pieceBounds("classic", type, "WHITE")[3];
  const blackHeight = pieceBounds("classic", type, "BLACK")[3];
  return Math.max(whiteHeight, blackHeight) / 362;
}
